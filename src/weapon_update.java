 void getphoto()
 {  try
       {
         int wid=Integer.parseInt(jComboBox1.getSelectedItem().toString());
         PreparedStatement ps=mycon.prepareStatement("select photo from weapons where weapon_id='"+wid+"'");  
         rs=ps.executeQuery();  
        if(rs.next())
        {
            Blob b=rs.getBlob(1);//2 means 2nd column data  
            byte barr[]=b.getBytes(1,(int)b.length());//1 means first image  
            FileOutputStream fout=new FileOutputStream("c:\\images\\temp.jpg");  
            fout.write(barr);  
            fout.close();  
            ImageIcon imageIcon = new ImageIcon(new ImageIcon("c:\\images\\temp.jpg").getImage().getScaledInstance(120, 120, Image.SCALE_DEFAULT));

            jLabel7.setIcon(imageIcon);
       }
       }
        catch(SQLException e)
        {
            jOptionPane1.showMessageDialog(this,"Error "+e,"Error",0);
        }
        catch(IOException e)
         {
            jOptionPane1.showMessageDialog(this,"Error "+e,"Error",0);
         }
 
 
 }
