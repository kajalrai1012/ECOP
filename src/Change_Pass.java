    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try{
            String current ,oldpass,newpass,conpass,sql;
            char[] p1=jPasswordField1.getPassword();
            char[] p2=jPasswordField2.getPassword();
            char[] p3=jPasswordField3.getPassword();
            oldpass=new String(p1);
            newpass=new String (p2);
            conpass=new String(p3);
            if(newpass.equals(conpass))
            {
                sql="select password from users where username='"+Login.cuser+"'";
                rs=stmt.executeQuery(sql);
                rs.next();
                current=rs.getString(1);
                if(current.equals(oldpass))
                {
                 sql="update users set password='"+newpass+"'where username='"+Login.cuser+"'";
                 stmt.executeUpdate(sql);
                 jOptionPane1.showMessageDialog(this,"Password successfully changed");
                 clear();
                } else
            {
                jOptionPane1.showMessageDialog(this,"Current Password is not correct","Error",0);
            }
            }
            else
            {
                jOptionPane1.showMessageDialog(this,"Passwords do not match","Error",0);
            }
            
        }
        catch(SQLException e)
        {
         jOptionPane1.showMessageDialog(this,"Error"+e,"Error",0);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

